const LOCALES = Object.keys(DICT);
const byTag = { 'zh-CN': 'zh', 'zh-Hans': 'zh', zh: 'zh', en: 'en', 'en-US': 'en', 'en-GB': 'en' };

export function normalizeLocale(value) {
  const raw = String(value ?? '').trim();
  if (LOCALES.includes(raw)) return raw;
  if (byTag[raw]) return byTag[raw];
  const short = raw.split('-')[0];
  return LOCALES.includes(short) ? short : null;
}

export function detectLocale() {
  const fromQuery = normalizeLocale(new URLSearchParams(location.search).get('lang'));
  if (fromQuery) return fromQuery;
  try {
    const stored = normalizeLocale(localStorage.getItem('codex-reset.locale'));
    if (stored) return stored;
  } catch {
    /* storage disabled */
  }
  const fromPath = normalizeLocale((location.pathname.match(/^\/([a-z]{2})(?:-[A-Za-z]+)?\//) || [])[1]);
  if (fromPath) return fromPath;
  return normalizeLocale(navigator.language) ?? 'zh';
}

export const LOCALE_LABEL = { zh: '中文', en: 'English' };

export function translator(locale) {
  const table = DICT[locale] || DICT.zh;
  return function t(key, params = {}) {
    const entry = table[key] ?? DICT.en[key] ?? DICT.zh[key];
    if (entry === undefined) return key;
    if (typeof entry !== 'function') {
      return Object.keys(params).length
        ? entry.replace(/\{(\w+)\}/g, (match, name) => (params[name] === undefined ? match : String(params[name])))
        : entry;
    }
    return entry(params);
  };
}

